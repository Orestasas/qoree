#!/usr/bin/env python3
"""Writes src/js/02-logos.js: exchange logos as data URIs (128 px WebP, re-encoded at quality 88 from CoinGecko's
exchange listings),
keyed by the normalised name Qubic's official exchange labels use, with each logo's main colour.
Usage: python3 src/gen_logos.py src/logos src/js/02-logos.js"""
import base64, os, sys
src, out = sys.argv[1], sys.argv[2]
# key: (file, main colour as "r g b" for the details light)
LOGOS = {
  'gateio': ('gateio.webp', '0 96 240'),
  'mexc': ('mexc.webp', '16 88 240'),
  'bitget': ('bitget.webp', '96 224 240'),
  'safetrade': ('safetrade.webp', '16 144 192'),
  'coinex': ('coinex.webp', '0 192 176'),
  'bit2me': ('bit2me.webp', '0 64 144'),
}
lines = []
for key, (name, rgb) in LOGOS.items():
    data = open(os.path.join(src, name), 'rb').read()
    mime = 'image/webp'
    lines.append(f"  {key}: {{ rgb: '{rgb}', src: 'data:{mime};base64,{base64.b64encode(data).decode()}' }},")
js = """// ═══════════════════════════════════════════════════════════════════════════
// 3b. EXCHANGE LOGOS: for the exchanges in Qubic's official address labels, as 128 px images
// (from CoinGecko's exchange listings; trademarks of their owners). Generated by gen_logos.py.
// Keyed by the label's name, lower-cased, without punctuation or a trailing number ("Bitget 2" → bitget).
// ═══════════════════════════════════════════════════════════════════════════
const EXCHANGE_LOGOS = Object.freeze({
""" + "\n".join(lines) + """
});
const logoKey = (name) => String(name || '').toLowerCase().replace(/[^a-z0-9]/g, '').replace(/\\d+$/, '');
const exchangeLogo = (key) => (Object.hasOwn(EXCHANGE_LOGOS, key) ? EXCHANGE_LOGOS[key] : null);
"""
open(out, 'w', encoding='utf-8').write(js)
print(f'wrote {len(LOGOS)} logos, {len(js)} bytes')
